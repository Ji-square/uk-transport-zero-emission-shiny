# prepare_data.R
# Run once, locally, from the folder that holds the raw files listed below.
# It reads the raw datasets (~90 MB) and writes one small file,
# data/app_data.rds, which is the only data the Shiny app loads.
# Deploying the .rds instead of the raw CSVs makes the app start in
# seconds and keeps the bundle small enough for the free shinyapps.io tier.
#
# Raw inputs (same folder as this script, or set RAW_DIR):
#   uk_country.geojson
#   electricity_consumption_region.csv
#   electricity_data.xlsx
#   national-charge-point-registry.csv
#   ulev_clean.csv
#   uk-local-authority-ghg-emissions-2020-dataset.csv

suppressPackageStartupMessages({
  library(dplyr)
  library(tidyr)
  library(readr)
  library(readxl)
  library(sf)
})

RAW_DIR <- Sys.getenv("RAW_DIR", ".")
raw <- function(f) file.path(RAW_DIR, f)

# ---------------------------------------------------------------------------
# Country boundaries
# Simplified in British National Grid (metres) so the polygons stay accurate
# at UK scale while the browser receives far fewer vertices.
# ---------------------------------------------------------------------------
uk <- st_read(raw("uk_country.geojson"), quiet = TRUE) |>
  select(country = geo_label) |>
  st_transform(27700) |>
  st_simplify(preserveTopology = TRUE, dTolerance = 500) |>
  st_transform(4326)

# ---------------------------------------------------------------------------
# Transport CO2 emissions (only 4 of the ~70 MB are needed)
# ---------------------------------------------------------------------------
co2 <- read_csv(
  raw("uk-local-authority-ghg-emissions-2020-dataset.csv"),
  col_select = c(Country, `Calendar Year`, `LA GHG Sector`,
                 `Greenhouse gas`, `Territorial emissions (kt CO2e)`),
  show_col_types = FALSE
) |>
  filter(Country != "Unallocated",
         `Greenhouse gas` == "CO2",
         `LA GHG Sector` == "Transport") |>
  group_by(country = Country, year = `Calendar Year`) |>
  summarise(mean_co2 = mean(`Territorial emissions (kt CO2e)`, na.rm = TRUE),
            .groups = "drop")

# ---------------------------------------------------------------------------
# Charge points
# ---------------------------------------------------------------------------
charge_point <- read_csv(
  raw("national-charge-point-registry.csv"),
  col_select = c(chargeDeviceID, name, latitude, longitude,
                 street, postcode, deviceOwnerName, dateCreated),
  col_types = cols(.default = col_character(),
                   latitude = col_double(), longitude = col_double()),
  show_col_types = FALSE
) |>
  mutate(year = suppressWarnings(as.integer(substr(dateCreated, 1, 4)))) |>
  filter(!is.na(year), year > 0, !is.na(latitude), !is.na(longitude)) |>
  mutate(label = sprintf(
    "<strong>Name:</strong> %s<br/><strong>Street:</strong> %s<br/><strong>Post code:</strong> %s<br/><strong>Owner:</strong> %s",
    name, street, postcode, deviceOwnerName
  )) |>
  select(year, latitude, longitude, label)

charge_point_cum <- charge_point |>
  count(year, name = "new") |>
  arrange(year) |>
  mutate(total = cumsum(new))

# ---------------------------------------------------------------------------
# Electric vehicles (ULEV licensing statistics)
# ---------------------------------------------------------------------------
ulev <- read_csv(raw("ulev_clean.csv"), show_col_types = FALSE) |>
  rename(territory = Geography,
         period = `Date Interval [note 3]`,
         types = `BodyType [note 2]`)

vehicles_gb <- ulev |>
  filter(territory == "Great Britain", period == "Annual", Units == "Number",
         types != "Total", type != "Total") |>
  group_by(date, types) |>
  summarise(total = sum(count), .groups = "drop")

vehicles_tab <- ulev |>
  filter(type != "Total", types != "Total") |>
  group_by(territory, period, date, types) |>
  summarise(total = sum(count), .groups = "drop")

# ---------------------------------------------------------------------------
# Electricity generated by source
# ---------------------------------------------------------------------------
electricity_gen <- read_excel(raw("electricity_data.xlsx"), na = "-") |>
  pivot_longer(-ano, names_to = "source", values_to = "gwh") |>
  filter(source != "used_on_works", !is.na(gwh)) |>
  mutate(date = as.Date(paste0(ano, "-01-01"))) |>
  select(date, source, gwh)

# ---------------------------------------------------------------------------
# Electricity consumed by country / region
# ---------------------------------------------------------------------------
electricity_tab <- read_csv(raw("electricity_consumption_region.csv"),
                            show_col_types = FALSE) |>
  filter(`Local authority` != "All local authorities",
         !`Country or region` %in% c("Great Britain (unallocated)",
                                     "England and Wales (unallocated)",
                                     "Scotland (unallocated)")) |>
  group_by(territory = `Country or region`, year) |>
  summarise(total_consumption_gwh = sum(consumption, na.rm = TRUE),
            .groups = "drop") |>
  mutate(period = "Annual", date = as.Date(paste0(year, "-01-01")))

# ---------------------------------------------------------------------------
dir.create("data", showWarnings = FALSE)
saveRDS(
  list(
    uk               = uk,
    co2              = co2,
    charge_point     = charge_point,
    charge_point_cum = charge_point_cum,
    vehicles_gb      = vehicles_gb,
    vehicles_tab     = vehicles_tab,
    electricity_gen  = electricity_gen,
    electricity_tab  = electricity_tab
  ),
  "data/app_data.rds",
  compress = "xz"
)
message("Wrote data/app_data.rds (", round(file.size("data/app_data.rds") / 1e6, 2), " MB)")
